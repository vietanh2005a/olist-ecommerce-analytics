-- DESCRIPTION: Monthly Customer Cohort Retention Matrix & Cohort LTV Expansion

USE OlistEcommerce;
GO

CREATE OR ALTER VIEW dbo.vw_cohort_retention_metrics AS
WITH Customer_First_Purchase AS (
    -- Identify cohort origin: customer's very first order date
    SELECT 
        c.customer_unique_id,
        MIN(o.order_purchase_timestamp) AS first_order_timestamp,
        DATEFROMPARTS(YEAR(MIN(o.order_purchase_timestamp)), MONTH(MIN(o.order_purchase_timestamp)), 1) AS cohort_month
    FROM dbo.orders o
    INNER JOIN dbo.customers c ON o.customer_id = c.customer_id
    WHERE o.order_status = 'delivered'
    GROUP BY c.customer_unique_id
),
Customer_All_Orders AS (
    -- All valid purchases and revenue generated by customer
    SELECT 
        c.customer_unique_id,
        o.order_id,
        DATEFROMPARTS(YEAR(o.order_purchase_timestamp), MONTH(o.order_purchase_timestamp), 1) AS order_month,
        SUM(oi.price + oi.freight_value) AS order_revenue
    FROM dbo.orders o
    INNER JOIN dbo.customers c ON o.customer_id = c.customer_id
    INNER JOIN dbo.order_items oi ON o.order_id = oi.order_id
    WHERE o.order_status = 'delivered'
    GROUP BY c.customer_unique_id, o.order_id, DATEFROMPARTS(YEAR(o.order_purchase_timestamp), MONTH(o.order_purchase_timestamp), 1)
),
Cohort_Activity AS (
    -- Calculate period offset and aggregate revenue per cohort per period
    SELECT 
        cao.customer_unique_id,
        cfp.cohort_month,
        cao.order_month,
        DATEDIFF(month, cfp.cohort_month, cao.order_month) AS period_number,
        cao.order_revenue
    FROM Customer_All_Orders cao
    INNER JOIN Customer_First_Purchase cfp ON cao.customer_unique_id = cfp.customer_unique_id
),
Cohort_Sizes AS (
    SELECT 
        cohort_month,
        COUNT(DISTINCT customer_unique_id) AS cohort_size,
        SUM(order_revenue) AS initial_cohort_revenue
    FROM Cohort_Activity
    WHERE period_number = 0
    GROUP BY cohort_month
),
Cohort_Aggregates AS (
    SELECT 
        ca.cohort_month,
        cs.cohort_size,
        ca.period_number,
        COUNT(DISTINCT ca.customer_unique_id) AS active_retained_customers,
        SUM(ca.order_revenue) AS period_revenue,
        CAST(COUNT(DISTINCT ca.customer_unique_id) * 100.0 / cs.cohort_size AS DECIMAL(5, 2)) AS retention_rate_pct,
        CAST(SUM(ca.order_revenue) / cs.cohort_size AS DECIMAL(10, 2)) AS period_revenue_per_acquired_customer
    FROM Cohort_Activity ca
    INNER JOIN Cohort_Sizes cs ON ca.cohort_month = cs.cohort_month
    GROUP BY ca.cohort_month, cs.cohort_size, ca.period_number
)
SELECT 
    cohort_month,
    FORMAT(cohort_month, 'yyyy-MM') AS cohort_label,
    cohort_size,
    period_number,
    active_retained_customers,
    period_revenue,
    retention_rate_pct,
    period_revenue_per_acquired_customer,
    SUM(period_revenue) OVER (
        PARTITION BY cohort_month 
        ORDER BY period_number 
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
    ) AS cumulative_cohort_revenue,
    CAST(
        SUM(period_revenue) OVER (
            PARTITION BY cohort_month 
            ORDER BY period_number 
            ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
        ) / cohort_size 
        AS DECIMAL(10, 2)
    ) AS cumulative_ltv_per_customer
FROM Cohort_Aggregates;
GO

-- 1. RETENTION RATE MATRIX (Period 0 to 12)
SELECT 
    cohort_month,
    FORMAT(cohort_month, 'yyyy-MM') AS cohort_label,
    cohort_size,
    MAX(CASE WHEN period_number = 0 THEN retention_rate_pct END) AS M0,
    MAX(CASE WHEN period_number = 1 THEN retention_rate_pct END) AS M1,
    MAX(CASE WHEN period_number = 2 THEN retention_rate_pct END) AS M2,
    MAX(CASE WHEN period_number = 3 THEN retention_rate_pct END) AS M3,
    MAX(CASE WHEN period_number = 4 THEN retention_rate_pct END) AS M4,
    MAX(CASE WHEN period_number = 5 THEN retention_rate_pct END) AS M5,
    MAX(CASE WHEN period_number = 6 THEN retention_rate_pct END) AS M6,
    MAX(CASE WHEN period_number = 7 THEN retention_rate_pct END) AS M7,
    MAX(CASE WHEN period_number = 8 THEN retention_rate_pct END) AS M8,
    MAX(CASE WHEN period_number = 9 THEN retention_rate_pct END) AS M9,
    MAX(CASE WHEN period_number = 10 THEN retention_rate_pct END) AS M10,
    MAX(CASE WHEN period_number = 11 THEN retention_rate_pct END) AS M11,
    MAX(CASE WHEN period_number = 12 THEN retention_rate_pct END) AS M12
FROM dbo.vw_cohort_retention_metrics
WHERE cohort_month >= '2017-01-01' AND cohort_month <= '2018-07-01'
GROUP BY cohort_month, cohort_size
ORDER BY cohort_month;
GO

-- 2. CUMULATIVE LTV EXPANSION MATRIX (Customer Lifetime Value per Acquired User)
SELECT 
    cohort_month,
    FORMAT(cohort_month, 'yyyy-MM') AS cohort_label,
    cohort_size,
    MAX(CASE WHEN period_number = 0 THEN cumulative_ltv_per_customer END) AS LTV_M0,
    MAX(CASE WHEN period_number = 1 THEN cumulative_ltv_per_customer END) AS LTV_M1,
    MAX(CASE WHEN period_number = 3 THEN cumulative_ltv_per_customer END) AS LTV_M3,
    MAX(CASE WHEN period_number = 6 THEN cumulative_ltv_per_customer END) AS LTV_M6,
    MAX(CASE WHEN period_number = 12 THEN cumulative_ltv_per_customer END) AS LTV_M12
FROM dbo.vw_cohort_retention_metrics
WHERE cohort_month >= '2017-01-01' AND cohort_month <= '2018-07-01'
GROUP BY cohort_month, cohort_size
ORDER BY cohort_month;
GO
